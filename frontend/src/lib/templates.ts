// 근로계약서를 아직 받지 못했을 때 보낼 교부 요청 문구 (근거: 근로기준법 제17조)
export function contractRequestText(company?: string | null): string {
  const where = company ? `${company} 채용에` : "채용에";
  return [
    "안녕하세요.",
    `${where} 지원한 지원자입니다.`,
    "근무를 시작하기 전에 임금, 근로시간, 휴일, 연차휴가 등 근로조건이 적힌 근로계약서를 미리 받아 볼 수 있을까요?",
    "근로기준법 제17조에 근로조건을 서면으로 명시해 교부하도록 되어 있다고 알고 있어 여쭙습니다.",
    "확인 부탁드립니다. 감사합니다.",
  ].join("\n");
}
